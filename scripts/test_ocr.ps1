    $lang = [Windows.Globalization.Language]::new("en-US")
    $engine = [Windows.Media.Ocr.OcrEngine]::TryCreateFromLanguage($lang)
}
Write-Output "Engine: $($engine.RecognizerLanguage.LanguageTag)"
